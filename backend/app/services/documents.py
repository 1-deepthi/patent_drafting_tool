"""DOCX assembly and PDF conversion for generated patent documents.

The built-in layout is always available. When an active `.docx` template
exists for the document type, `docxtpl` renders the documented placeholders
in that template instead (letterhead/layout stays under the template
author's control). PDF output shells out to headless LibreOffice, which the
Docker image installs.
"""
import io
import os
import shutil
import subprocess
import tempfile
from pathlib import Path

from docx import Document
from docx.shared import Pt, RGBColor

SECTION_ORDER = (
    ("ABSTRACT", "Abstract"),
    ("BACKGROUND", "Background"),
    ("SUMMARY", "Summary"),
    ("DESCRIPTION", "Detailed Description"),
    ("CLAIMS", "Claims"),
)

DOCUMENT_TYPES = (
    "Patent Application",
    "Provisional Specification",
    "Complete Specification",
    "PCT Application",
)

KNOWN_PLACEHOLDERS = (
    "TITLE",
    "WATERMARK_TEXT",
    "ABSTRACT",
    "BACKGROUND",
    "SUMMARY",
    "DESCRIPTION",
    "CLAIMS",
)

WATERMARK_TEXT = (
    "DRAFT — NOT LEGAL ADVICE. For professional review only; not for filing as-is."
)

DISCLAIMER = (
    "This document was generated by the Patent Filing & Lifecycle Management "
    "Platform as a drafting aid. It is not legal advice and must be reviewed by "
    "a qualified patent professional before filing."
)


class DocumentGenerationError(RuntimeError):
    pass


def _value(sections: dict, key: str) -> str:
    value = sections.get(key)
    return str(value).strip() if value not in (None, "") else "Not generated."


def build_context(patent: dict, sections: dict) -> dict:
    return {
        "TITLE": patent.get("invention_title") or "Untitled invention",
        "WATERMARK_TEXT": WATERMARK_TEXT,
        "ABSTRACT": _value(sections, "ABSTRACT"),
        "BACKGROUND": _value(sections, "BACKGROUND"),
        "SUMMARY": _value(sections, "SUMMARY"),
        "DESCRIPTION": _value(sections, "DESCRIPTION"),
        "CLAIMS": _value(sections, "CLAIMS"),
    }


def inspect_template(content: bytes) -> tuple[list[str], list[str], str | None]:
    """Return (unknown_placeholders, unused_known_placeholders, parse_error)."""
    try:
        from docxtpl import DocxTemplate

        template = DocxTemplate(io.BytesIO(content))
        used = set(template.get_undeclared_template_variables())
    except Exception as exc:  # noqa: BLE001 - reported to the uploader
        return [], [], str(exc)
    unknown = sorted(v for v in used if v not in KNOWN_PLACEHOLDERS)
    unused = sorted(v for v in KNOWN_PLACEHOLDERS if v not in used)
    return unknown, unused, None


def _render_builtin(patent: dict, sections: dict) -> bytes:
    document = Document()

    style = document.styles["Normal"]
    style.font.name = "Calibri"
    style.font.size = Pt(11)

    watermark = document.add_paragraph()
    run = watermark.add_run(WATERMARK_TEXT)
    run.bold = True
    run.font.color.rgb = RGBColor(0xC0, 0x00, 0x00)

    document.add_heading(build_context(patent, sections)["TITLE"], level=0)

    for key, label in SECTION_ORDER:
        document.add_heading(label, level=1)
        for paragraph in _value(sections, key).split("\n\n"):
            document.add_paragraph(paragraph.strip())

    document.add_paragraph()
    disclaimer = document.add_paragraph()
    disclaimer_run = disclaimer.add_run(DISCLAIMER)
    disclaimer_run.italic = True
    disclaimer_run.font.size = Pt(9)
    disclaimer_run.font.color.rgb = RGBColor(0x60, 0x60, 0x60)

    buffer = io.BytesIO()
    document.save(buffer)
    return buffer.getvalue()


def render_docx(patent: dict, sections: dict, template: bytes | None) -> bytes:
    context = build_context(patent, sections)
    if template:
        try:
            from docxtpl import DocxTemplate

            document = DocxTemplate(io.BytesIO(template))
            document.render(context)
            buffer = io.BytesIO()
            document.save(buffer)
            return buffer.getvalue()
        except Exception as exc:  # noqa: BLE001
            raise DocumentGenerationError(
                f"The active DOCX template could not be rendered: {exc}"
            ) from exc
    return _render_builtin(patent, sections)


def pdf_available() -> bool:
    """True when a LibreOffice binary is available for DOCX→PDF conversion."""
    return _soffice_binary() is not None


def _soffice_binary() -> str | None:
    for candidate in ("soffice", "libreoffice"):
        found = shutil.which(candidate)
        if found:
            return found
    # Common Windows install locations during local development.
    for candidate in (
        r"C:\Program Files\LibreOffice\program\soffice.exe",
        r"C:\Program Files (x86)\LibreOffice\program\soffice.exe",
    ):
        if Path(candidate).is_file():
            return candidate
    return None


def docx_to_pdf(content: bytes) -> bytes:
    binary = _soffice_binary()
    if not binary:
        raise DocumentGenerationError(
            "PDF conversion requires LibreOffice (`soffice`). Install it locally "
            "or use the Docker image, which includes it. DOCX generation works "
            "without it."
        )
    with tempfile.TemporaryDirectory(prefix="patent-pdf-") as folder:
        source = Path(folder) / "document.docx"
        source.write_bytes(content)
        environment = dict(os.environ)
        environment.setdefault("HOME", folder)
        try:
            result = subprocess.run(
                [
                    binary,
                    "--headless",
                    "--norestore",
                    "--convert-to",
                    "pdf",
                    "--outdir",
                    folder,
                    str(source),
                ],
                capture_output=True,
                timeout=120,
                check=False,
                env=environment,
            )
        except subprocess.TimeoutExpired as exc:
            raise DocumentGenerationError("PDF conversion timed out.") from exc
        target = Path(folder) / "document.pdf"
        if result.returncode != 0 or not target.is_file():
            detail = (result.stderr or result.stdout or b"").decode(
                "utf-8", errors="replace"
            )[:400]
            raise DocumentGenerationError(f"LibreOffice could not convert the DOCX: {detail}")
        return target.read_bytes()
